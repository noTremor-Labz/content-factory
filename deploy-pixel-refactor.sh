#!/bin/bash

# deploy-pixel-refactor.sh
# Рефактор Pixel: универсальный агент + platform-specs
# Запускать из корня проекта: content-factory/

set -e

SOULS="souls"
SHARED="shared"
PLATFORM_SPECS="$SHARED/platform-specs"

echo "📁 Создаём shared/platform-specs/..."
mkdir -p "$PLATFORM_SPECS"

# ── telegram.md ──────────────────────────────────────────────
cat > "$PLATFORM_SPECS/telegram.md" << 'EOF'
# Platform Spec — Telegram

## Формат публикации
- Тип: текстовый пост с одним изображением
- Длина текста: 800–1800 символов
- Изображение: обязательно, прикрепляется к посту

## Структура поста
1. Первые 1–2 строки — хук (без обрезки в превью)
2. Основной текст — абзацами по 2–4 строки, пустая строка между ними
3. Финал — вывод или вопрос к аудитории
4. TL;DR — последний блок, отделён пустой строкой

## Оформление
- Эмодзи: умеренно, 1–3 на пост, только по смыслу
- Хэштеги: 0–3, в конце поста
- Жирный текст: **слово** — для ключевых терминов, не для красоты
- Курсив: не использовать
- Списки: допустимы, если контент реально списочный

## Изображение
- Соотношение сторон: 1:1 или 4:5
- Параметры генерации: --ar 1:1 --style raw --v 6.1

## Чего избегать
- Кликбейт в хуке
- Стена текста без абзацев
- Более 3 хэштегов
EOF

# ── youtube-shorts.md ─────────────────────────────────────────
cat > "$PLATFORM_SPECS/youtube-shorts.md" << 'EOF'
# Platform Spec — YouTube Shorts

## Формат публикации
- Тип: вертикальное видео с субтитрами
- Длительность: 30–60 секунд (оптимум 45 сек)
- Соотношение сторон: 9:16

## Структура видео
1. 0–3 сек — хук: визуальный или вербальный, без вступления
2. 3–40 сек — основной контент, одна мысль без отступлений
3. 40–60 сек — вывод + CTA (подписка или следующее видео)

## Оформление
- Субтитры: обязательны, крупный шрифт, центр кадра
- Текстовые оверлеи: максимум 1 одновременно
- Заголовок видео: до 60 символов, хук = заголовок
- Описание: 1–2 строки + 3–5 хэштегов

## Изображение (превью/обложка)
- Соотношение сторон: 9:16
- Параметры генерации: --ar 9:16 --style raw --v 6.1
- Текст на превью: крупно, 3–5 слов максимум

## Темп монтажа
- Cuts каждые 2–4 секунды
- Без затяжных статичных кадров
- Музыка: фоновая, не перекрывает голос

## Чего избегать
- Вступления типа "привет, сегодня мы поговорим о..."
- Горизонтальный контент без адаптации
- Субтитры мелким шрифтом
EOF

# ── instagram-reels.md ────────────────────────────────────────
cat > "$PLATFORM_SPECS/instagram-reels.md" << 'EOF'
# Platform Spec — Instagram Reels

## Формат публикации
- Тип: вертикальное видео
- Длительность: 15–90 секунд (оптимум 30–45 сек)
- Соотношение сторон: 9:16

## Структура видео
1. 0–2 сек — хук: визуальный удар, без вступления
2. 2–35 сек — контент: быстро, плотно, без воды
3. Последние 3–5 сек — CTA: сохранить, поделиться, подписаться

## Оформление
- Субтитры: обязательны, крупный шрифт
- Текстовые оверлеи: стилизованные, соответствуют бренду блоггера
- Описание поста: до 150 символов видимой части + хэштеги
- Хэштеги: 5–10, в конце описания или первый комментарий
- Обложка (cover): отдельный кадр, не стоп-кадр из видео

## Изображение (обложка)
- Соотношение сторон: 9:16
- Параметры генерации: --ar 9:16 --style raw --v 6.1
- Текст на обложке: крупно, 2–4 слова

## Темп монтажа
- Cuts каждые 1–3 секунды
- Trending audio или оригинальный звук
- Первые 2 секунды без лого и титров

## Чего избегать
- Watermark TikTok или других платформ
- Длинные статичные кадры
- Текст у краёв кадра (safe zone: отступ 15% с каждой стороны)
EOF

# ── tiktok.md ────────────────────────────────────────────────
cat > "$PLATFORM_SPECS/tiktok.md" << 'EOF'
# Platform Spec — TikTok

## Формат публикации
- Тип: вертикальное видео
- Длительность: 15–60 секунд (оптимум 20–35 сек)
- Соотношение сторон: 9:16

## Структура видео
1. 0–1.5 сек — хук: максимально резкий, без раскачки
2. 1.5–30 сек — контент: одна идея, быстро, разговорно
3. Финал — открытый вопрос или незавершённая мысль (провоцирует комменты)

## Оформление
- Субтитры: обязательны, крупный шрифт, анимированные предпочтительно
- Текстовые оверлеи: нативный TikTok-стиль или кастомный бренд
- Описание: 1–2 строки разговорного текста + 3–5 хэштегов
- Хэштеги: 3–5, микс нишевых и широких

## Изображение (обложка)
- Соотношение сторон: 9:16
- Параметры генерации: --ar 9:16 --style raw --v 6.1
- Текст на обложке: 2–4 слова, крупно

## Темп монтажа
- Cuts каждые 1–2 секунды
- Trending sound обязателен или оригинальный голос
- Петля (loop): конец видео плавно переходит в начало — буст просмотров

## Чего избегать
- Вступления длиннее 1.5 секунд
- Горизонтальные кадры
- Watermark других платформ
- Стоковые футажи без обработки
EOF

echo "✅ platform-specs созданы"

# ── pixel.md (универсальный) ──────────────────────────────────
echo "📝 Создаём souls/pixel.md..."
cat > "$SOULS/pixel.md" << 'EOF'
# PIXEL — Визуал (универсальный)

## Кто я
Создаю промпты для изображений и видео-обложек к публикациям блоггеров.
Работаю с любой площадкой и любым блоггером — правила беру из задачи и shared файлов.

## Входные данные задачи
Обязательные поля:
- `блогер` — имя блоггера (tomas / misha / yulya / nasik)
- `канал` — тема/ниша (food / vibe / и т.д.), если есть
- `платформа` — площадка (telegram / youtube-shorts / instagram-reels / tiktok)

## Алгоритм
1. Прочитать research.md из папки задачи
2. Прочитать визуальный бренд блоггера:
   - Если есть канал: /home/node/shared/bloggers/{блогер}/brand/visual-{канал}.md
   - Если нет: /home/node/shared/bloggers/{блогер}/brand/visual.md
3. Прочитать правила площадки: /home/node/shared/platform-specs/{платформа}.md
4. Создать промпт для Midjourney/image-gen:
   - Позитивная часть (что должно быть на изображении)
   - Negative prompt (что исключить)
   - Параметры соотношения сторон — взять из platform-spec
5. Сохранить как image_prompt.txt в папку задачи
6. Ответить Director'у: "✅ image_prompt.txt готов. PIXEL_DONE"

## Правила
- Визуальный стиль (цвета, настроение, запреты) — из brand файла блоггера
- Технические параметры (ar, формат) — из platform-spec площадки
- Промпт всегда на английском
- Не изобретать стиль самостоятельно — только из источников
EOF

echo "✅ souls/pixel.md создан"

# ── routing-director.md ───────────────────────────────────────
echo "📝 Обновляем souls/routing-director.md..."
cat > "$SOULS/routing-director.md" << 'EOF'
# Роутинг агентов по блогерам и каналам

## tomas
- food: quill (универсальный), lens, pixel, launch-tomas-tg-food
- vibe: quill, lens, pixel, launch-tomas-tg-vibe

## misha
- yt: quill, lens, pixel, launch-misha-yt

## yulya
- ig: quill, lens, pixel, launch-yulya-ig

## nasik
- tt: quill, lens, pixel, launch-nasik-tt

## Формат задачи
тема: [тема] | платформа: [telegram|youtube-shorts|instagram-reels|tiktok] | формат: пост | блогер: [tomas|misha|yulya|nasik] | канал: [food|vibe|yt|ig|tt]

## Примечания
- pixel — универсальный агент, один для всех блоггеров и площадок
- pixel читает визуальный бренд из /home/node/shared/bloggers/{блогер}/brand/
- pixel читает правила площадки из /home/node/shared/platform-specs/{платформа}.md
- Все поля формата задачи обязательны для корректной работы pixel
EOF

echo "✅ souls/routing-director.md обновлён"

# ── Удаляем старые pixel souls ────────────────────────────────
echo "🗑️  Удаляем старые pixel souls..."
OLD_PIXELS=(
  "$SOULS/pixel-tomas.md"
  "$SOULS/pixel-misha-yt.md"
  "$SOULS/pixel-yulya-ig.md"
  "$SOULS/pixel-nasik-tt.md"
)

for f in "${OLD_PIXELS[@]}"; do
  if [ -f "$f" ]; then
    rm "$f"
    echo "   удалён: $f"
  else
    echo "   не найден (пропуск): $f"
  fi
done

echo ""
echo "✅ Готово. Итог:"
echo "   shared/platform-specs/ — 4 файла"
echo "   souls/pixel.md — универсальный агент"
echo "   souls/routing-director.md — обновлён"
echo "   старые pixel souls — удалены"
